#!/usr/bin/env node
// Generates the data-testid contract from src/testing/selectors.json into
// src/testing/testids.gen.ts (Testids.group.key -> id). The app passes the ids
// to testID props; the auto-test-suite imports the same file and builds
// [data-testid="..."] selectors from it.
// Run with --check to fail (exit 1) when the committed file is out of date.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src/testing/selectors.json');
const tsOut = join(root, 'src/testing/testids.gen.ts');

const spec = JSON.parse(readFileSync(source, 'utf8'));
const header = 'Code generated by scripts/gen-selectors.mjs from src/testing/selectors.json. DO NOT EDIT.';

function validate() {
  const seen = new Map();
  for (const [group, entries] of Object.entries(spec)) {
    if (!/^[a-z][A-Za-z0-9]*$/.test(group)) throw new Error(`group "${group}" must be camelCase`);
    for (const [key, id] of Object.entries(entries)) {
      if (!/^[a-z][A-Za-z0-9]*$/.test(key)) throw new Error(`${group}.${key} must be camelCase`);
      if (!/^[a-z0-9-]+$/.test(id)) throw new Error(`${group}.${key} id "${id}" must be kebab-case`);
      if (seen.has(id)) throw new Error(`duplicate testid "${id}" in ${group}.${key} and ${seen.get(id)}`);
      seen.set(id, `${group}.${key}`);
    }
  }
}

function renderTs() {
  const lines = [`// ${header}`, '', 'export const Testids = {'];
  for (const [group, entries] of Object.entries(spec)) {
    lines.push(`  ${group}: {`);
    for (const [key, id] of Object.entries(entries)) lines.push(`    ${key}: '${id}',`);
    lines.push('  },');
  }
  lines.push('} as const;', '');
  return lines.join('\n');
}

validate();
const outputs = [[tsOut, renderTs()]];

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text);
  if (stale.length) {
    for (const [path] of stale) console.error(`selectors: out of date: ${path.replace(root + '/', '')}`);
    console.error('selectors: run `npm run selectors:gen` and commit the result');
    process.exit(1);
  }
  console.log('selectors: generated files are up to date');
} else {
  for (const [path, text] of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    console.log(`selectors: wrote ${path.replace(root + '/', '')}`);
  }
}
